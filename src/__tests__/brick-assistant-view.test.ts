import { mount } from '@vue/test-utils'
import { afterEach, describe, expect, it, vi } from 'vitest'
import BrickAssistantView from '../views/BrickAssistantView.vue'

describe('砖了个砖助手交互', () => {
  afterEach(() => vi.useRealTimers())
  it('示例可计算、模拟消除并撤销，修改砖块后重新计算', async () => {
    vi.useFakeTimers()
    const wrapper = mount(BrickAssistantView)
    await wrapper.get('[data-test="demo"]').trigger('click')
    expect(wrapper.findAll('.brick-cell:not(.empty)')).toHaveLength(12)
    expect(wrapper.findAll('.move-option').length).toBeGreaterThan(0)
    await wrapper.get('[data-test="apply"]').trigger('click')
    expect(wrapper.findAll('.clearing')).toHaveLength(2)
    expect(wrapper.findAll('.brick-cell:not(.empty)')).toHaveLength(12)
    await vi.advanceTimersByTimeAsync(1200)
    expect(wrapper.findAll('.brick-cell:not(.empty)')).toHaveLength(10)
    await wrapper.get('[data-test="undo"]').trigger('click')
    expect(wrapper.findAll('.brick-cell:not(.empty)')).toHaveLength(12)
    await wrapper.get('[data-test=edit-toggle]').trigger('click')
    await wrapper.get('.brick-cell').trigger('click')
    await wrapper.get('[data-test="set-empty"]').trigger('click')
    expect(wrapper.findAll('.brick-cell:not(.empty)')).toHaveLength(11)
    wrapper.unmount()
  })
  it('只演示不修改棋盘，导入新示例会取消旧动画', async () => {
    vi.useFakeTimers()
    const wrapper = mount(BrickAssistantView)
    await wrapper.get('[data-test=demo]').trigger('click')
    await wrapper.get('[data-test=preview]').trigger('click')
    expect(wrapper.findAll('.clearing')).toHaveLength(2)
    await vi.advanceTimersByTimeAsync(1200)
    expect(wrapper.findAll('.brick-cell:not(.empty)')).toHaveLength(12)
    expect(wrapper.findAll('.clearing')).toHaveLength(0)
    await wrapper.get('[data-test=apply]').trigger('click')
    await wrapper.get('[data-test=demo]').trigger('click')
    await vi.advanceTimersByTimeAsync(1200)
    expect(wrapper.findAll('.brick-cell:not(.empty)')).toHaveLength(12)
    wrapper.unmount()
  })
  it('先把四块一起右推，再消除鸡腿，撤销恢复整行', async () => {
    vi.useFakeTimers()
    const wrapper = mount(BrickAssistantView)
    await wrapper.get('[data-test=push-demo]').trigger('click')
    expect(wrapper.findAll('.brick-cell:not(.empty)')).toHaveLength(10)
    await wrapper.get('[data-test=apply]').trigger('click')
    expect(wrapper.findAll('.pushing-tile')).toHaveLength(4)
    expect(wrapper.findAll('.clearing')).toHaveLength(0)
    await vi.advanceTimersByTimeAsync(750)
    expect(wrapper.findAll('.pushing-tile')).toHaveLength(0)
    expect(wrapper.findAll('.clearing')).toHaveLength(2)
    expect(wrapper.findAll('.brick-cell')[1].attributes('aria-label')).toContain('图案 1')
    expect(wrapper.findAll('.brick-cell')[2].attributes('aria-label')).toContain('图案 2')
    await vi.advanceTimersByTimeAsync(1100)
    expect(wrapper.findAll('.brick-cell:not(.empty)')).toHaveLength(8)
    expect(wrapper.findAll('.brick-cell')[1].classes()).toContain('empty')
    await wrapper.get('[data-test=undo]').trigger('click')
    expect(wrapper.findAll('.brick-cell:not(.empty)')).toHaveLength(10)
    expect(wrapper.findAll('.brick-cell')[0].attributes('aria-label')).toContain('图案 1')
    expect(wrapper.findAll('.brick-cell')[1].attributes('aria-label')).toContain('图案 2')
    wrapper.unmount()
  })
  it('推动预览和中途取消均恢复位置，不留下被推动的砖块', async () => {
    vi.useFakeTimers()
    const wrapper = mount(BrickAssistantView)
    await wrapper.get('[data-test=push-demo]').trigger('click')
    await wrapper.get('[data-test=preview]').trigger('click')
    await vi.advanceTimersByTimeAsync(1850)
    expect(wrapper.findAll('.brick-cell')[0].attributes('aria-label')).toContain('图案 1')
    expect(wrapper.findAll('.brick-cell:not(.empty)')).toHaveLength(10)
    await wrapper.get('[data-test=apply]').trigger('click')
    await vi.advanceTimersByTimeAsync(750)
    await wrapper.get('[data-test=stop]').trigger('click')
    await vi.advanceTimersByTimeAsync(2000)
    expect(wrapper.findAll('.brick-cell')[0].attributes('aria-label')).toContain('图案 1')
    expect(wrapper.findAll('.brick-cell')[1].attributes('aria-label')).toContain('图案 2')
    expect(wrapper.findAll('.brick-cell:not(.empty)')).toHaveLength(10)
    wrapper.unmount()
  })
  it('无屏幕采集能力时提供可操作提示', async () => {
    const wrapper = mount(BrickAssistantView)
    await wrapper.get('[data-test="capture"]').trigger('click')
    expect(wrapper.get('[role="alert"]').text()).toContain('截图')
    wrapper.unmount()
  })
})
