async function submitGuess() {
  const guess = draft.value
  const active = challenge.value
  attempts.value++
  history.value = [guess, ...history.value].slice(0, 6)

  let correct = false
  if (active) {
    // 挑战模式：本地根本没有密码，只能拿令牌现场跑一次 KDF
    verifying.value = true
    const started = performance.now()
    try {
      correct = await verifyChallenge(active, guess)
    } catch {
      correct = false
      errorText.value = '校验失败，请刷新页面重试'
    } finally {
      verifying.value = false
      verifySeconds.value = (performance.now() - started) / 1000
    }
  } else {
    correct = guess === passcode.value
  }

  if (correct) {
    draft.value = ''
    errorText.value = ''
    lockoutRemaining.value = 0
    phase.value = 'unlocked'
    return
  }

  failedAttempts.value++

  const lockout = getLockoutSeconds(failedAttempts.value)
  const remaining = getRemainingAttemptsBeforeLockout(failedAttempts.value)

  if (lockout > 0) {
    lockoutRemaining.value = lockout
    errorText.value = ''
  } else {
    errorText.value = `密码错误，还可尝试 ${remaining} 次`
  }

  flashError()
}

function flashError(message = '') {
  if (message) errorText.value = message
  errorFlash.value = true
  shaking.value = true

  if (shakeTimer) clearTimeout(shakeTimer)
  shakeTimer = setTimeout(() => {
    shaking.value = false
  }, 500)

  // 抖动结束后再清空输入的密码点
  if (clearTimer) clearTimeout(clearTimer)
  clearTimer = setTimeout(() => {
    errorFlash.value = false
    draft.value = ''
  }, 600)
}

function tick() {
  now.value = new Date()

  if (phase.value === 'locked') {
    elapsed.value++
  }

  if (lockoutRemaining.value > 0) {
    lockoutRemaining.value--
  }
}

function handleKeydown(event: KeyboardEvent) {
  const target = event.target as HTMLElement | null
  if (target && (target.tagName === 'INPUT' || target.tagName === 'TEXTAREA')) return

  if (/^\d$/.test(event.key)) {
    handleDigit(event.key)
  } else if (event.key === 'Backspace') {
    handleDelete()
  } else if (event.key === 'Escape') {
    showHint.value = false
  }
}

function handleHashChange() {
  const token = readChallengeFromUrl()
  const parsed = parseChallenge(token)
  if (parsed && encodeChallenge(parsed) !== (challenge.value && encodeChallenge(challenge.value))) {
    enterChallenge(parsed)
  }
}

onMounted(() => {
  tickTimer = setInterval(tick, 1000)
  window.addEventListener('keydown', handleKeydown)
  window.addEventListener('hashchange', handleHashChange)

  const parsed = parseChallenge(readChallengeFromUrl())
  if (parsed) enterChallenge(parsed)
})

onUnmounted(() => {
  if (tickTimer) clearInterval(tickTimer)
  if (shakeTimer) clearTimeout(shakeTimer)
  if (clearTimer) clearTimeout(clearTimer)
  window.removeEventListener('keydown', handleKeydown)
  window.removeEventListener('hashchange', handleHashChange)
})
</script>

