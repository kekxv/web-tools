  { id: 'neon', name: '霓虹', preview: 'linear-gradient(140deg, #180033, #a3167a 50%, #35b6ff)' },
  { id: 'midnight', name: '午夜', preview: 'linear-gradient(140deg, #05070f, #14213c 55%, #3d8fbf)' }
]

const HOME_APPS = [
  { name: '电话', icon: '📞', background: 'linear-gradient(160deg, #4ade80, #16a34a)' },
  { name: '信息', icon: '💬', background: 'linear-gradient(160deg, #60a5fa, #2563eb)' },
  { name: '相机', icon: '📷', background: 'linear-gradient(160deg, #4b5563, #111827)' },
  { name: '照片', icon: '🖼️', background: 'linear-gradient(160deg, #fbbf24, #f97316)' },
  { name: '音乐', icon: '🎵', background: 'linear-gradient(160deg, #fb7185, #e11d48)' },
  { name: '天气', icon: '⛅', background: 'linear-gradient(160deg, #38bdf8, #0284c7)' },
  { name: '日历', icon: '📅', background: 'linear-gradient(160deg, #f8fafc, #cbd5e1)' },
  { name: '设置', icon: '⚙️', background: 'linear-gradient(160deg, #94a3b8, #475569)' }
]

const DOCK_APPS = [
  { name: '电话', icon: '📞', background: 'linear-gradient(160deg, #4ade80, #16a34a)' },
  { name: '浏览器', icon: '🧭', background: 'linear-gradient(160deg, #60a5fa, #1d4ed8)' },
  { name: '信息', icon: '💬', background: 'linear-gradient(160deg, #34d399, #059669)' },
  { name: '音乐', icon: '🎵', background: 'linear-gradient(160deg, #fb7185, #e11d48)' }
]

const phase = ref<Phase>('setup')
const setupStep = ref<SetupStep>('enter')
const passcodeLength = ref<PasscodeLength>(4)
const draft = ref('')
const firstPasscode = ref('')
const passcode = ref('')
const hintText = ref('')
const autoGenerated = ref(false)

const attempts = ref(0)
const failedAttempts = ref(0)
const history = ref<string[]>([])
const elapsed = ref(0)
const lockoutRemaining = ref(0)

const shaking = ref(false)
const errorFlash = ref(false)
const errorText = ref('')
const showHint = ref(false)

const wallpaper = ref('aurora')
const now = ref(new Date())

// 挑战模式：密码不在本地，只有一个只能校验、不能反解的令牌
const challenge = ref<Challenge | null>(null)
const verifying = ref(false)

// 分享面板
const shareToken = ref('')
const shareLink = ref('')
const shareState = ref<'idle' | 'generating' | 'ready'>('idle')
const shareError = ref('')
const copied = ref('')
const tokenInput = ref('')
const tokenError = ref('')
const verifySeconds = ref(0)

let tickTimer: ReturnType<typeof setInterval> | undefined
let shakeTimer: ReturnType<typeof setTimeout> | undefined
let clearTimer: ReturnType<typeof setTimeout> | undefined

const clockTime = computed(() => {
  const h = String(now.value.getHours()).padStart(2, '0')
  const m = String(now.value.getMinutes()).padStart(2, '0')
  return `${h}:${m}`
})

const clockDate = computed(() => {
  const d = now.value
  return `${d.getMonth() + 1}月${d.getDate()}日 ${WEEKDAYS[d.getDay()]}`
})

const formattedElapsed = computed(() => formatDuration(elapsed.value))
const isLockedOut = computed(() => lockoutRemaining.value > 0)
const isGuessing = computed(() => phase.value === 'locked')
const remainingBeforeLockout = computed(() =>
  getRemainingAttemptsBeforeLockout(failedAttempts.value)
)

const isChallengeMode = computed(() => challenge.value !== null)

const phaseChip = computed(() => {
  if (phase.value === 'setup') return { label: '设置密码中', tone: 'setup' }
  if (phase.value === 'unlocked') {
    return isChallengeMode.value
      ? { label: '挑战成功', tone: 'done' }
      : { label: '已解锁', tone: 'done' }
  }
  if (phase.value === 'handoff') return { label: '等待交给朋友', tone: 'wait' }
  if (isLockedOut.value) return { label: 'iPhone 已停用', tone: 'danger' }
  return isChallengeMode.value
    ? { label: '接受挑战中', tone: 'challenge' }
    : { label: '猜密码中', tone: 'run' }
})

// 对方离线穷举大概要多久（用本机实测的单次校验耗时估算）
const bruteForceText = computed(() => {
  if (!verifySeconds.value) return ''
  return formatRoughDuration(estimateBruteForceSeconds(passcodeLength.value, verifySeconds.value))
})

const verifyCostText = computed(() =>
  verifySeconds.value ? `${verifySeconds.value.toFixed(2)} 秒` : ''
)

const promptText = computed(() => {
  if (verifying.value) return '校验中…'
  if (isLockedOut.value) return 'iPhone 已停用'
  return showHint.value && hintText.value ? `💡 ${hintText.value}` : '输入密码'
})

const setupTitle = computed(() => (setupStep.value === 'enter' ? '设置密码' : '请再次输入'))
const setupTip = computed(() =>
  setupStep.value === 'enter' ? '输入完成后会自动进入下一步' : '两次输入需要保持一致'
)

function handleDigit(digit: string) {
  if (phase.value === 'setup') {
    if (setupStep.value === 'hint' || draft.value.length >= passcodeLength.value) return
    errorText.value = ''
    draft.value += digit
    if (draft.value.length === passcodeLength.value) {
      completeSetupEntry()
    }
    return
  }

  if (phase.value === 'locked') {
    if (verifying.value || isLockedOut.value || draft.value.length >= passcodeLength.value) return
    errorText.value = ''
    draft.value += digit
    if (draft.value.length === passcodeLength.value) {
      submitGuess()
    }
  }
}

function handleDelete() {
  if (phase.value === 'setup') {
    if (setupStep.value === 'hint') return
    draft.value = draft.value.slice(0, -1)
    return
  }
  if (phase.value === 'locked' && !isLockedOut.value) {
    draft.value = draft.value.slice(0, -1)
  }
}

function completeSetupEntry() {
  if (setupStep.value === 'enter') {
    firstPasscode.value = draft.value
    draft.value = ''
    setupStep.value = 'confirm'
    return
  }

  if (draft.value === firstPasscode.value) {
    passcode.value = draft.value
    draft.value = ''
    autoGenerated.value = false
    setupStep.value = 'hint'
  } else {
    firstPasscode.value = ''
    draft.value = ''
    setupStep.value = 'enter'
    flashError('两次输入不一致，请重新设置')
  }
}

function changePasscodeLength(length: PasscodeLength) {
  if (passcodeLength.value === length) return
  passcodeLength.value = length
  draft.value = ''
  firstPasscode.value = ''
  setupStep.value = 'enter'
  errorText.value = ''
}

function useRandomPasscode() {
  passcode.value = randomPasscode(passcodeLength.value)
  firstPasscode.value = passcode.value
  draft.value = ''
  autoGenerated.value = true
  setupStep.value = 'hint'
}

function lockPhone() {
  passcodeLength.value = passcode.value.length as PasscodeLength
  resetRound()
  phase.value = 'handoff'
}

function startGuessing() {
  resetRound()
  phase.value = 'locked'
}

function relockSamePasscode() {
  resetRound()
  phase.value = 'handoff'
}

function resetRound() {
  attempts.value = 0
  failedAttempts.value = 0
  history.value = []
  elapsed.value = 0
  lockoutRemaining.value = 0
  draft.value = ''
  errorText.value = ''
  showHint.value = false
  errorFlash.value = false
  shaking.value = false
}

function resetGame() {
  resetRound()
  phase.value = 'setup'
  setupStep.value = 'enter'
  passcodeLength.value = 4
  passcode.value = ''
  firstPasscode.value = ''
  hintText.value = ''
  autoGenerated.value = false
  challenge.value = null
  shareToken.value = ''
  shareLink.value = ''
  shareState.value = 'idle'
  shareError.value = ''
  tokenError.value = ''
  clearChallengeInUrl()
}

/**
 * 进入挑战模式：只保留令牌，密码本身不进内存
 */
function enterChallenge(next: Challenge) {
  challenge.value = next
  passcodeLength.value = next.length
  passcode.value = ''
  hintText.value = ''
  resetRound()
  setupStep.value = 'enter'
  phase.value = 'locked'
}

/** 从 #/phone-lock?c=xxx 里读挑战码 */
function readChallengeFromUrl(): string | null {
  try {
    const hash = window.location.hash || ''
    const index = hash.indexOf('?')
    if (index === -1) return null
    return new URLSearchParams(hash.slice(index + 1)).get('c')
  } catch {
    return null
  }
}

function clearChallengeInUrl() {
  try {
    if (readChallengeFromUrl()) {
      window.history.replaceState(null, '', `${window.location.pathname}#/phone-lock`)
    }
  } catch {
    /* 忽略：地址栏清理失败不影响玩 */
  }
}

function acceptToken() {
  const token = tokenInput.value.trim()
  if (!token) return
  const parsed = parseChallenge(token)
  if (!parsed) {
    tokenError.value = '挑战码无法识别，可能被聊天软件截断了，让对方重新发一次'
    return
  }
  tokenError.value = ''
  tokenInput.value = ''
  enterChallenge(parsed)
}

/**
 * 生成分享链接：链接里只有令牌，没有密码
 */
async function generateShareLink() {
  if (!passcode.value || shareState.value === 'generating') return
  shareState.value = 'generating'
  shareError.value = ''
  try {
    const next = await createChallenge(passcode.value)
    const token = encodeChallenge(next)
    shareToken.value = token
    shareLink.value = `${window.location.origin}${window.location.pathname}#/phone-lock?c=${token}`
    shareState.value = 'ready'

    // 顺手实测一次本机校验耗时，用来估算对方离线穷举的成本
    const started = performance.now()
    await verifyChallenge(next, passcode.value)
    verifySeconds.value = (performance.now() - started) / 1000
  } catch (error) {
    shareState.value = 'idle'
    shareError.value = error instanceof Error ? error.message : '生成失败，请重试'
  }
}

async function copyText(text: string, tag: string): Promise<boolean> {
  try {
    if (navigator.clipboard?.writeText) {
      await navigator.clipboard.writeText(text)
      copied.value = tag
      setTimeout(() => {
        if (copied.value === tag) copied.value = ''
      }, 2000)
      return true
    }
  } catch {
    /* 继续走下面的兜底 */
  }
  try {
    const area = document.createElement('textarea')
    area.value = text
    area.setAttribute('readonly', 'readonly')
    area.style.position = 'fixed'
    area.style.opacity = '0'
    document.body.appendChild(area)
    area.select()
    const ok = document.execCommand('copy')
    area.remove()
    copied.value = ok ? tag : ''
    return ok
  } catch {
    return false
  }
}

function selectShareInput(event: FocusEvent) {
  const target = event.target as HTMLInputElement | null
  target?.select()
}

