<script setup lang="ts">
import { computed, onMounted, onUnmounted, ref } from 'vue'
import PasscodeKeypad from '../components/PhoneLock/PasscodeKeypad.vue'
import {
  ATTEMPTS_BEFORE_LOCKOUT,
  PASSCODE_LENGTHS,
  formatCountdown,
  formatDuration,
  formatRoughDuration,
  getLockoutSeconds,
  getRemainingAttemptsBeforeLockout,
  randomPasscode,
  type PasscodeLength
} from '../utils/phone-lock'
import {
  createChallenge,
  encodeChallenge,
  estimateBruteForceSeconds,
  parseChallenge,
  verifyChallenge,
  type Challenge
} from '../utils/phone-lock-challenge'

type Phase = 'setup' | 'handoff' | 'locked' | 'unlocked'
type SetupStep = 'enter' | 'confirm' | 'hint'

const WEEKDAYS = ['星期日', '星期一', '星期二', '星期三', '星期四', '星期五', '星期六']

// 锁屏墙纸（preview 用于面板上的色卡）
const WALLPAPERS = [
